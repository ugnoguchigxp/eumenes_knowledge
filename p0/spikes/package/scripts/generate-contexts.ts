// Generates src/contexts/generated.ts from src/contexts/sources/<id>.v<N>.md.
// `--check` fails when the committed file differs (used by verify).
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const sourceDir = join(root, "src/contexts/sources");
const target = join(root, "src/contexts/generated.ts");
const sha256 = (value: string) =>
	createHash("sha256").update(value).digest("hex");

const entries = readdirSync(sourceDir)
	.filter((name) => name.endsWith(".md"))
	.sort()
	.map((name) => {
		const match = /^([a-z0-9-]+)\.v(\d+)\.md$/.exec(name);
		if (!match) throw new Error(`bad instruction file name: ${name}`);
		const text = readFileSync(join(sourceDir, name), "utf8");
		return {
			id: match[1] as string,
			version: Number(match[2]),
			sha256: sha256(text),
			text,
		};
	});

const output = `// GENERATED by scripts/generate-contexts.ts from src/contexts/sources. Do not edit.
export const instructionEntries = ${JSON.stringify(entries, null, "\t")} as const;
export const INSTRUCTION_SET_DIGEST = ${JSON.stringify(sha256(entries.map((e) => `${e.id}@${e.version}:${e.sha256}`).join("\n")))};
`;

if (process.argv.includes("--check")) {
	const current = existsSync(target) ? readFileSync(target, "utf8") : "";
	if (current !== output) {
		console.error("src/contexts/generated.ts is stale; run contexts:generate");
		process.exit(1);
	}
	console.log("contexts: generated.ts is current");
} else {
	writeFileSync(target, output);
	console.log(`contexts: wrote ${entries.length} instruction(s)`);
}
