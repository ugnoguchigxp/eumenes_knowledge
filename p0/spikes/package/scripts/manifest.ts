// Writes distribution-manifest.json (inside the package) after build.
// Deterministic: no timestamps, sorted keys, LF.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { pathToFileURL } from "node:url";

const root = join(import.meta.dir, "..");
const sha256 = (data: string | Uint8Array) =>
	createHash("sha256").update(data).digest("hex");

function walk(dir: string): string[] {
	return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
		const full = join(dir, entry.name);
		return entry.isDirectory() ? walk(full) : [full];
	});
}
const rel = (path: string) => relative(root, path).split("\\").join("/");
const hashFiles = (paths: string[]) =>
	Object.fromEntries(
		paths
			.map(rel)
			.sort()
			.map((path) => [path, sha256(readFileSync(join(root, path)))]),
	);
const digestOf = (files: Record<string, string>) =>
	sha256(
		Object.entries(files)
			.map(([path, hash]) => `${path}\0${hash}`)
			.join("\n"),
	);

const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const dist = await import(pathToFileURL(join(root, "dist/index.js")).href);
const sqlite = await import(
	pathToFileURL(join(root, "dist/sqlite/index.js")).href
);

// Source digest scope: everything that determines dist, nothing generated by it.
const sourcePaths = [
	...walk(join(root, "src")),
	...walk(join(root, "scripts")),
	...[
		"package.json",
		"bun.lock",
		"bunfig.toml",
		"tsconfig.json",
		"tsconfig.build.json",
	].map((f) => join(root, f)),
].filter((path) => existsSync(path));
const sourceFiles = hashFiles(sourcePaths);

// Published files = what `files` ships, minus this manifest itself.
const shipped = [
	...walk(join(root, "dist")),
	...["package.json", "LICENSE", "THIRD_PARTY_NOTICES.md"].map((f) =>
		join(root, f),
	),
];
const distributionFiles = hashFiles(shipped);

function git(args: string[]): string | null {
	const result = Bun.spawnSync(["git", ...args], { cwd: root });
	return result.exitCode === 0 ? result.stdout.toString().trim() : null;
}
const commit = git(["rev-parse", "HEAD"]);
const dirty =
	commit === null ? null : (git(["status", "--porcelain"]) ?? "") !== "";

const version = (cmd: string[]) =>
	Bun.spawnSync(cmd, { cwd: root }).stdout.toString().trim();

const manifest = {
	kind: "eumenes-knowledge-distribution",
	manifestVersion: 1,
	package: { name: pkg.name, version: pkg.version, license: pkg.license },
	contract: { version: dist.CONTRACT_VERSION },
	instructions: {
		setDigest: dist.INSTRUCTION_SET_DIGEST,
		entries: dist.instructions.map(
			(i: { id: string; version: number; sha256: string }) => ({
				id: i.id,
				version: i.version,
				sha256: i.sha256,
			}),
		),
	},
	schema: {
		migrationCount: sqlite.migrations.length,
		// Same function as Eumenes' schema_migrations_v2.checksum: sha256 hex of the SQL string.
		migrations: (sqlite.migrations as string[]).map((sql, index) => ({
			ordinal: index + 1,
			id: String(index + 1).padStart(4, "0"),
			sha256: sha256(sql),
		})),
	},
	exports: Object.keys(pkg.exports),
	bin: pkg.bin,
	dependencies: pkg.dependencies,
	source: {
		gitCommit: commit,
		dirty,
		note:
			commit === null ? "spike directory is not a git repository" : undefined,
		digest: digestOf(sourceFiles),
		digestScope:
			"src/**, scripts/**, package.json, bun.lock, bunfig.toml, tsconfig*.json (sorted path+sha256)",
		fileCount: Object.keys(sourceFiles).length,
	},
	distribution: {
		digest: digestOf(distributionFiles),
		digestScope:
			"dist/**, package.json, LICENSE, THIRD_PARTY_NOTICES.md (this manifest excluded)",
		files: distributionFiles,
	},
	toolchain: {
		bun: version(["bun", "--version"]),
		typescript: version([
			join(root, "node_modules/.bin/tsc"),
			"--version",
		]).replace(/^Version /, ""),
	},
	lightrag: {
		status: "unfilled",
		upstream: "https://github.com/HKUDS/LightRAG",
		commit: null,
		license: "MIT",
		files: [],
		note: "filled when the first port lands (P2)",
	},
};

writeFileSync(
	join(root, "distribution-manifest.json"),
	`${JSON.stringify(manifest, null, "\t")}\n`,
);
console.log(`manifest: distribution.digest=${manifest.distribution.digest}`);
