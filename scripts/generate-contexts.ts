// Generates src/contexts/generated.ts from src/contexts/sources/<id>.v<N>.md.
// `--check` fails when the file on disk differs from what would be generated (used by verify).
// Zero instruction files is a valid state (P1 ships none; extraction instructions arrive in P2).
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { repoRoot, sha256 } from "./lib/common.js";

export type InstructionSource = {
	id: string;
	version: number;
	sha256: string;
	text: string;
};

const fileNamePattern = /^([a-z][a-z0-9-]*)\.v([1-9][0-9]*)\.md$/;

/** `id@version:sha256` lines, joined by LF, hashed. Same value the manifest re-derives. */
export function instructionSetDigest(
	entries: readonly Pick<InstructionSource, "id" | "version" | "sha256">[],
): string {
	return sha256(
		entries.map((e) => `${e.id}@${e.version}:${e.sha256}`).join("\n"),
	);
}

/** Reads `<id>.v<N>.md` files; a missing directory means no instructions. */
export function readInstructionSources(sourceDir: string): InstructionSource[] {
	if (!existsSync(sourceDir)) return [];
	const entries = readdirSync(sourceDir, { withFileTypes: true })
		.filter((entry) => entry.isFile())
		.map((entry) => entry.name)
		.map((name) => {
			const match = fileNamePattern.exec(name);
			if (!match) throw new Error(`bad instruction file name: ${name}`);
			const text = readFileSync(join(sourceDir, name), "utf8");
			if (text.includes("\r")) {
				throw new Error(`instruction file must use LF line endings: ${name}`);
			}
			return {
				id: match[1] as string,
				version: Number(match[2]),
				sha256: sha256(text),
				text,
			};
		});
	return entries.sort((a, b) =>
		a.id < b.id ? -1 : a.id > b.id ? 1 : a.version - b.version,
	);
}

/** The exact text of generated.ts for these sources. */
export function renderGenerated(entries: readonly InstructionSource[]): string {
	const body =
		entries.length === 0 ? "[]" : JSON.stringify(entries, null, "\t");
	return `// GENERATED by scripts/generate-contexts.ts from src/contexts/sources. Do not edit.
export interface InstructionEntry {
	readonly id: string;
	readonly version: number;
	readonly sha256: string;
	readonly text: string;
}
export const instructionEntries: readonly InstructionEntry[] = ${body};
export const INSTRUCTION_SET_DIGEST: string = ${JSON.stringify(instructionSetDigest(entries))};
`;
}

export type GenerateResult = { ok: boolean; message: string };

export function generateContexts(options: {
	root: string;
	check: boolean;
}): GenerateResult {
	const sourceDir = join(options.root, "src/contexts/sources");
	const target = join(options.root, "src/contexts/generated.ts");
	const entries = readInstructionSources(sourceDir);
	const output = renderGenerated(entries);
	if (options.check) {
		const current = existsSync(target) ? readFileSync(target, "utf8") : null;
		return current === output
			? {
					ok: true,
					message: `contexts: generated.ts is current (${entries.length} instruction(s))`,
				}
			: {
					ok: false,
					message:
						"contexts: src/contexts/generated.ts is stale; run `bun run contexts:generate`",
				};
	}
	writeFileSync(target, output);
	return {
		ok: true,
		message: `contexts: wrote ${entries.length} instruction(s)`,
	};
}

if (import.meta.main) {
	const result = generateContexts({
		root: repoRoot,
		check: process.argv.includes("--check"),
	});
	(result.ok ? console.log : console.error)(result.message);
	process.exit(result.ok ? 0 : 1);
}
